function bindReadingNotes(ci) {
  const chapter = chapters[ci];
  const guide = readingGuides[chapter.course.slug]?.[chapter.index];
  if (!guide) return;
  const article = main.querySelector("article");
  const theory = article.querySelector("section");
  const overview = document.createElement("p");
  overview.className = "plain-language";
  const label = document.createElement("strong");
  label.textContent = "쉽게 말하면";
  overview.append(label, document.createTextNode(guide.summary));
  theory.querySelector("h2").after(overview);

  const used = new Map();
  const terms = guide.terms
    .map(([term]) => term)
    .sort((a, b) => b.length - a.length);
  const pattern = new RegExp(
    terms.map((term) => term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"),
    "g",
  );
  const paragraphs = article.querySelectorAll(
    ".plain-language, .topic p, .panel td, .panel th, .panel > p, .note li, .solution-steps li",
  );
  for (const paragraph of paragraphs) {
    const walker = document.createTreeWalker(paragraph, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      const text = node.textContent;
      const fragment = document.createDocumentFragment();
      let offset = 0;
      for (const match of text.matchAll(pattern)) {
        const term = match[0];
        if (used.has(term)) continue;
        const number = used.size + 1;
        used.set(term, number);
        fragment.append(
          document.createTextNode(text.slice(offset, match.index) + term),
        );
        const reference = document.createElement("button");
        reference.type = "button";
        reference.className = "footnote-ref";
        reference.id = `reading-ref-${number}`;
        reference.dataset.term = term;
        reference.setAttribute("aria-haspopup", "dialog");
        reference.setAttribute("aria-controls", "term-dialog");
        reference.setAttribute("aria-label", `${term} 뜻, 각주 ${number}`);
        reference.textContent = `[${number}]`;
        fragment.append(reference);
        offset = match.index + term.length;
      }
      if (offset) {
        fragment.append(document.createTextNode(text.slice(offset)));
        node.replaceWith(fragment);
      }
    }
  }
  if (!used.size) return;
  const dialog = document.createElement("dialog");
  dialog.id = "term-dialog";
  dialog.className = "term-dialog";
  dialog.setAttribute("aria-labelledby", "term-dialog-title");
  dialog.setAttribute("aria-describedby", "term-dialog-copy");
  const heading = document.createElement("h2");
  heading.id = "term-dialog-title";
  const copy = document.createElement("p");
  copy.id = "term-dialog-copy";
  const close = document.createElement("button");
  close.type = "button";
  close.className = "term-dialog-close";
  close.textContent = "닫기";
  close.autofocus = true;
  dialog.append(heading, copy, close);
  article.append(dialog);

  let trigger;
  article.addEventListener("click", (event) => {
    const reference = event.target.closest(".footnote-ref");
    if (!reference) return;
    trigger = reference;
    heading.textContent = reference.dataset.term;
    copy.textContent = guide.terms.find(
      ([term]) => term === reference.dataset.term,
    )[1];
    dialog.showModal();
  });
  close.addEventListener("click", () => dialog.close());
  dialog.addEventListener("click", (event) => {
    if (event.target !== dialog) return;
    const box = dialog.getBoundingClientRect();
    if (
      event.clientX < box.left ||
      event.clientX > box.right ||
      event.clientY < box.top ||
      event.clientY > box.bottom
    )
      dialog.close();
  });
  dialog.addEventListener("close", () =>
    trigger?.focus({ preventScroll: true }),
  );
}
